"""Letter-trigram counts of macOS's /usr/share/dict/words, for the Windows build.

On macOS, EnglishModel trains its letter trigrams at runtime on /usr/share/dict/words (web2,
Webster's Second International, public domain). Windows has no such file, so the counts are
taken once from Apple's copy and shipped as crates/core/data/spelling_trigrams.txt; build.rs
adds EnglishModel's extra words on top, exactly as the macOS model does.

usage: python3 build_spelling_trigrams.py [web2 file] > ../crates/core/data/spelling_trigrams.txt
Without a file it downloads Apple's web2 and checks it is the one macOS ships.
"""
import hashlib
import sys
import urllib.request
from collections import Counter

URL = "https://raw.githubusercontent.com/apple-oss-distributions/files/main/usr/share/dict/web2"
MD5 = "f920f969528c6adf9fec6e803470083d"  # 235,976 words


def main():
    if len(sys.argv) > 1:
        data = open(sys.argv[1], "rb").read()
    else:
        data = urllib.request.urlopen(URL).read()
        if hashlib.md5(data).hexdigest() != MD5:
            sys.exit("web2 changed upstream: check it is still what macOS ships")
    counts = Counter()
    for line in data.decode("ascii").splitlines():
        word = line.lower()
        if not word or not all("a" <= c <= "z" for c in word):
            continue
        # [^, ^, letters..., $] with ^ and $ both written as _ (EnglishModel encodes both as 0)
        codes = "__" + word + "_"
        for i in range(2, len(codes)):
            counts[codes[i - 2:i + 1]] += 1
    out = sys.stdout
    out.write("# Letter trigrams of Apple's web2 (macOS /usr/share/dict/words), md5 " + MD5 + "\n")
    out.write("# _ = word boundary. Generated by windows/tools/build_spelling_trigrams.py\n")
    for trigram in sorted(counts):
        out.write(f"{trigram}\t{counts[trigram]}\n")


if __name__ == "__main__":
    main()
